# Builds web/src/summon/heroes.js: token id -> "skill:element" for every Mind (Hero Skill from Face, element from Skin).
import json, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cards = open(os.path.join(root, 'web/src/summon/cards.js'), encoding='utf-8').read()
def table(name):
    body = re.search(name + r' = \{([^}]*)\}', cards).group(1)
    return {k.strip().strip("'"): v.strip().strip("'") for k, v in re.findall(r"('?[\w ]+'?)\s*:\s*('\w+')", body)}
face, skin, lskill, lel = table('FACE_SKILL'), table('SKIN_ELEMENT'), table('LEGENDARY_SKILL'), table('LEGENDARY_ELEMENT')
tokens = json.load(open(os.path.join(root, 'web/data/tokens.json'), encoding='utf-8'))
out = {}
for tid, t in tokens.items():
    if t.get('Legendary'):
        out[tid] = f"{lskill[t['Legendary']]}:{lel[t['Legendary']]}"
    else:
        out[tid] = f"{face[t['Face']]}:{skin[t['Skin']]}"
with open(os.path.join(root, 'web/src/summon/heroes.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// token id -> "heroSkill:element" (generated by tools/build_heroes.py from the NFT traits)\n')
    f.write('export default ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'heroes')
